<?php
/**
 * One-time installer. Creates the database tables, the first admin user and includes/config.php.
 * DELETE the /install folder from the server when finished.
 */
require_once __DIR__ . '/../includes/functions.php';
header('X-Robots-Tag: noindex, nofollow');

$lock = __DIR__ . '/.lock';
$configFile = ROOT_DIR . '/includes/config.php';
$errors = [];
$done = false;

// Refuse to run again once installed.
if (is_file($lock)) {
    http_response_code(403);
    exit('Already installed. Delete the /install folder from your server.');
}

$guessBase = rtrim(str_replace('\\', '/', dirname(dirname($_SERVER['SCRIPT_NAME'] ?? '/install/install.php'))), '/');
$v = [
    'db_host' => 'localhost', 'db_name' => '', 'db_user' => '', 'db_pass' => '',
    'site_url' => ((!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https://' : 'http://') . ($_SERVER['HTTP_HOST'] ?? 'localhost') . $guessBase,
    'base_path' => $guessBase === '/' ? '' : $guessBase,
    'mail_to' => 'admin@mcattorneys.co.zw', 'mail_from' => '',
    'admin_name' => '', 'admin_email' => '',
];
$withSamples = true;

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_check();
    foreach ($v as $k => $_) { $v[$k] = trim((string) ($_POST[$k] ?? $v[$k])); }
    $pass = (string) ($_POST['admin_pass'] ?? '');
    $withSamples = !empty($_POST['samples']);

    if ($v['db_name'] === '' || $v['db_user'] === '') { $errors[] = 'Enter the database name and user created in cPanel → MySQL® Databases.'; }
    if ($v['admin_name'] === '') { $errors[] = 'Enter the administrator name.'; }
    if (!filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) { $errors[] = 'Enter a valid administrator email.'; }
    if (strlen($pass) < 10) { $errors[] = 'The administrator password must be at least 10 characters.'; }
    if ($v['mail_from'] !== '' && !filter_var($v['mail_from'], FILTER_VALIDATE_EMAIL)) { $errors[] = 'The "send from" email is not valid.'; }

    if (!$errors) {
        try {
            $pdo = new PDO("mysql:host={$v['db_host']};dbname={$v['db_name']};charset=utf8mb4", $v['db_user'], $v['db_pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
            $sql = file_get_contents(ROOT_DIR . '/sql/schema.sql');
            foreach (array_filter(array_map('trim', preg_split('/;\s*[\r\n]+/', $sql))) as $stmt) {
                if (!preg_match('/^--/', $stmt) || preg_match('/CREATE/i', $stmt)) {
                    $pdo->exec(preg_replace('/^--.*$/m', '', $stmt));
                }
            }
            $exists = (int) $pdo->query('SELECT COUNT(*) FROM users')->fetchColumn();
            if ($exists > 0) {
                $errors[] = 'This database already has an administrator. Installation stopped to protect existing data.';
            } else {
                $pdo->prepare('INSERT INTO users (name, email, password_hash) VALUES (?,?,?)')
                    ->execute([$v['admin_name'], strtolower($v['admin_email']), password_hash($pass, PASSWORD_DEFAULT)]);

                if ($withSamples) {
                    $covers = [
                        'what-to-know-before-transferring-property' => 'conveyancing.jpg', 'administering-a-deceased-estate' => 'estates.jpg',
                        'employer-duties-when-ending-employment' => 'labour.jpg', 'choosing-a-business-structure' => 'commercial.jpg',
                        'your-rights-when-arrested' => 'litigation.jpg', 'understanding-mining-title' => 'mining.jpg',
                        'mc-attorneys-opens-in-eastlea' => 'news.jpg',
                    ];
                    @mkdir(ROOT_DIR . '/uploads', 0755, true);
                    $ins = $pdo->prepare('INSERT IGNORE INTO posts (title, slug, excerpt, content, cover_image, category, author, status, published_at) VALUES (?,?,?,?,?,?,?,?,?)');
                    foreach (require __DIR__ . '/sample-posts.php' as [$slug, $cat, $title, $author, $date, $excerpt, $html]) {
                        $cover = $covers[$slug] ?? null;
                        $src = __DIR__ . '/sample-covers/' . $cover;
                        if ($cover && is_file($src)) { @copy($src, ROOT_DIR . '/uploads/' . $cover); @chmod(ROOT_DIR . '/uploads/' . $cover, 0644); } else { $cover = null; }
                        $ins->execute([$title, $slug, $excerpt, $html, $cover, $cat, $author, 'published', $date . ' 09:00:00']);
                    }
                }

                $cfg = [
                    'db_host' => $v['db_host'], 'db_name' => $v['db_name'], 'db_user' => $v['db_user'], 'db_pass' => $v['db_pass'],
                    'base_path' => $v['base_path'], 'site_url' => rtrim($v['site_url'], '/'),
                    'mail_to' => $v['mail_to'], 'mail_from' => $v['mail_from'] !== '' ? $v['mail_from'] : 'no-reply@' . preg_replace('/^www\./', '', (string) ($_SERVER['HTTP_HOST'] ?? 'localhost')),
                ];
                $php = "<?php\n// Generated by install.php — do not commit this file.\nreturn " . var_export($cfg, true) . ";\n";
                if (file_put_contents($configFile, $php, LOCK_EX) === false) {
                    $errors[] = 'Could not write includes/config.php. Make the includes folder writable (755/775) and try again.';
                } else {
                    @chmod($configFile, 0640);
                    @file_put_contents($lock, date('c'));
                    @mkdir(ROOT_DIR . '/uploads', 0755, true);
                    $done = true;
                }
            }
        } catch (Throwable $ex) {
            $errors[] = 'Database error: ' . $ex->getMessage();
        }
    }
}
