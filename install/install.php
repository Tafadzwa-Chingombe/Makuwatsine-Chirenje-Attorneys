    <label>Site URL <small>(no trailing slash)</small></label><input name="site_url" value="<?= e($v['site_url']) ?>" required>
    <label>Install folder <small>(blank if at the domain root)</small></label><input name="base_path" value="<?= e($v['base_path']) ?>">
    <label>Send contact enquiries to</label><input type="email" name="mail_to" value="<?= e($v['mail_to']) ?>" required>
    <label>Send enquiries from <small>(an address on your domain, e.g. no-reply@yourdomain.co.zw)</small></label><input type="email" name="mail_from" value="<?= e($v['mail_from']) ?>">
